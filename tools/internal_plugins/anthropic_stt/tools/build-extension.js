#!/usr/bin/env node
'use strict';

// Compiles selectors.json + the relay token into a plain script the extension
// can load. selectors.json stays the only hand-edited authority; --check fails
// when the generated copy drifts.

const fs = require('fs');
const path = require('path');
const { loadConfig } = require('../config_store');

const HERE = path.resolve(__dirname, '..');
const PORT = 17875;

function generatedPath(dir = HERE) {
  return path.join(dir, 'extension', 'generated', 'config.js');
}

function compile(options = {}) {
  const dir = options.dir || HERE;
  const selectors = JSON.parse(fs.readFileSync(path.join(dir, 'selectors.json'), 'utf8'));
  const { config, tokenMissing } = loadConfig(dir, { persist: options.persist !== false });
  const value = {
    token: config.relayToken,
    wsUrl: `ws://127.0.0.1:${PORT}/extension`,
    selectors,
  };
  return {
    tokenMissing,
    text: [
      '// Generated by tools/build-extension.js from selectors.json + config.json.',
      '// Do not edit this file; re-run the generator. Never commit it.',
      `self.ANTHROPIC_STT_CONFIG = ${JSON.stringify(value, null, 2)};`,
      '',
    ].join('\n'),
  };
}

function render(options = {}) {
  return compile(options).text;
}

function build(options = {}) {
  const dir = options.dir || HERE;
  const out = generatedPath(dir);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, compile({ ...options, persist: true }).text, 'utf8');
  return out;
}

function check(options = {}) {
  const dir = options.dir || HERE;
  const target = generatedPath(dir);
  const { text: expected, tokenMissing } = compile({ dir, persist: false });
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  return { ok: actual === expected && !tokenMissing, path: target, tokenMissing };
}

if (require.main === module) {
  const dir = HERE;
  if (process.argv.includes('--check')) {
    const result = check({ dir });
    if (!result.ok) {
      if (result.tokenMissing) {
        console.error('[anthropic-stt] generated extension config has no relay token yet; run the generator:');
      } else {
        console.error(`[anthropic-stt] generated extension config is OUT OF DATE: ${result.path}`);
        console.error('[anthropic-stt] run the generator:');
      }
      console.error('  node tools/internal_plugins/anthropic_stt/tools/build-extension.js');
      process.exit(1);
    }
    console.log(`[anthropic-stt] extension config is up to date: ${result.path}`);
  } else {
    const written = build({ dir });
    console.log(`[anthropic-stt] wrote ${written}`);
    console.log('[anthropic-stt] reload the unpacked extension in chrome://extensions to pick it up');
  }
}

module.exports = { PORT, build, check, generatedPath, render };
