#!/usr/bin/env node
'use strict';

// Compiles EVERY platform selector set + the one shared relay token into the
// single MV3 extension's generated config. selectors/<platform>.json stays the
// only hand-edited authority; --check fails when the generated copy drifts.

const fs = require('fs');
const path = require('path');
const { loadConfig, BRIDGE_DIR } = require('../config_store');
const diagnostics = require('../diagnostics');

const EXTENSION_DIR = path.join(BRIDGE_DIR, 'extension');
const PLATFORMS = ['claude', 'gemini', 'chatgpt'];
const LOG = '[stt-bridge]';

function generatedPath(options = {}) {
  return options.out || path.join(EXTENSION_DIR, 'generated', 'config.js');
}

function selectorsPath(platform) {
  return path.join(BRIDGE_DIR, 'selectors', `${platform}.json`);
}

function pluginDir(options = {}) {
  if (options.dir) return path.resolve(options.dir);
  const flag = process.argv.find((arg) => arg.startsWith('--plugin-dir='));
  if (flag) return path.resolve(flag.slice('--plugin-dir='.length));
  return path.resolve(BRIDGE_DIR, '..', '..', 'anthropic_stt');
}

function compile(options = {}) {
  const dir = pluginDir(options);
  const platforms = {};
  for (const name of PLATFORMS) {
    platforms[name] = JSON.parse(fs.readFileSync(selectorsPath(name), 'utf8'));
  }
  const { config, tokenMissing } = loadConfig(dir, {
    persist: options.persist !== false,
    tokenAuthority: options.tokenAuthority,
  });
  const value = {
    token: config.relayToken,
    wsUrl: `ws://127.0.0.1:${config.port}/extension`,
    platform: config.platform,
    platforms,
    diagnostics: diagnostics.enabled(),
  };
  return {
    tokenMissing,
    value,
    text: [
      '// Generated by _common/bridge/tools/build-extension.js.',
      '// Do not edit this file; re-run the generator. Never commit it.',
      `self.ANTHROPIC_STT_CONFIG = ${JSON.stringify(value, null, 2)};`,
      '',
    ].join('\n'),
  };
}

function render(options = {}) {
  return compile(options).text;
}

function build(options = {}) {
  const out = generatedPath(options);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, compile({ ...options, persist: options.persist !== false }).text, 'utf8');
  return out;
}

function check(options = {}) {
  const target = generatedPath(options);
  const { text: expected, tokenMissing } = compile({ ...options, persist: false });
  const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  // Two values belong to whoever installed the extension, not to the source:
  // the relay token (rotates when the app runs) and the active platform (the
  // install is generated for whichever plugin is selected). Everything else --
  // selectors, wsUrl, shape -- must still match byte for byte.
  return {
    ok: withoutRuntimeValues(actual) === withoutRuntimeValues(expected) && !tokenMissing,
    path: target,
    tokenMissing,
  };
}

function withoutRuntimeValues(text) {
  return text
    .replace(/"token":\s*"[^"]*"/, '"token":"<rotated>"')
    .replace(/"platform":\s*"[^"]*"/, '"platform":"<active>"')
    .replace(/"diagnostics":\s*(true|false)/, '"diagnostics":<dev>');
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const result = check();
    if (!result.ok) {
      if (result.tokenMissing) {
        console.error(`${LOG} generated extension config has no relay token yet; run the generator:`);
      } else {
        console.error(`${LOG} generated extension config is OUT OF DATE: ${result.path}`);
        console.error(`${LOG} run the generator:`);
      }
      console.error('  node tools/internal_plugins/_common/bridge/tools/build-extension.js');
      process.exit(1);
    }
    console.log(`${LOG} extension config is up to date: ${result.path}`);
  } else {
    const written = build();
    console.log(`${LOG} wrote ${written}`);
    console.log(`${LOG} reload the unpacked extension in chrome://extensions to pick it up`);
  }
}

module.exports = { PLATFORMS, build, check, compile, generatedPath, render, selectorsPath };
