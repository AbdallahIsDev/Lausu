#!/usr/bin/env python3
"""Provision the MSYS2/mingw-w64 linker shim for the x86_64-pc-windows-gnu target.

WHY THIS EXISTS
---------------
Windows dev machines without MSVC must link the Rust host with MSYS2/mingw-w64
GCC. That toolchain has two defects this shim papers over (see the header of
``src-tauri/toolchain/linker_wrap.c`` for the full story):

1. MSYS2 gcc forwards ABSOLUTE ``@response-file`` args to ``ld``, which has no
   response-file support -> ``ld.exe: cannot find @...: Invalid argument``.
2. rustc deletes its codegen artifacts while the slow gcc link is still reading
   them, and because rustc does not wait for the linker it still exits 0, so
   cargo marks a crate built even though its DLL does not exist.

The shim needs two generated artifacts, and BOTH used to live only in
gitignored directories with no way to rebuild them:

* ``src-tauri/.toolchain/linker-wrap.exe`` - compiled from the tracked source
* ``src-tauri/.cargo/config.toml``        - points cargo at the wrapper

That made a single missing 300 KB file an unrecoverable toolchain outage whose
only symptom was a misleading ``error: linker ... not found`` followed by dozens
of unrelated ``could not compile`` errors. Deleting the folder, an AV
quarantine, or a fresh clone all produced it.

This script is the missing regeneration path. It is idempotent, safe to run
repeatedly, and cheap: it only recompiles when the tracked source is newer than
the binary. Run it with no arguments to provision, or ``--check`` to verify
without writing anything (that is what the dev-loop preflight calls).

Usage:
    python scripts/build/ensure_gnu_linkchain.py            # provision/repair
    python scripts/build/ensure_gnu_linkchain.py --check    # verify only
    python scripts/build/ensure_gnu_linkchain.py --force    # always rebuild
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
SRC_TAURI = REPO_ROOT / "src-tauri"

# Tracked source of truth (committed; portable, discovers MSYS2 at runtime).
WRAPPER_SRC = SRC_TAURI / "toolchain" / "linker_wrap.c"

# Generated artifacts (gitignored; rebuildable from WRAPPER_SRC).
TOOLCHAIN_DIR = SRC_TAURI / ".toolchain"
WRAPPER_EXE = TOOLCHAIN_DIR / "linker-wrap.exe"
CARGO_CONFIG = SRC_TAURI / ".cargo" / "config.toml"

TARGET_TRIPLE = "x86_64-pc-windows-gnu"
GCC_EXE_NAME = "x86_64-w64-mingw32-gcc.exe"

# Searched in order. Mirrors find_gcc() in linker_wrap.c so the bootstrap and
# the wrapper itself can never disagree about which toolchain is in use.
GCC_SEARCH_ROOTS = (
    r"C:\msys64\mingw64\bin",
    r"C:\msys64\ucrt64\bin",
    r"C:\msys64\clang64\bin",
    r"C:\msys64\mingw32\bin",
    r"C:\mingw64\bin",
    r"C:\ProgramData\chocolatey\bin",
)

CONFIG_HEADER = """\
# GENERATED by scripts/build/ensure_gnu_linkchain.py - DO NOT EDIT BY HAND.
#
# Points cargo at the MSYS2/mingw-w64 linker shim for the GNU target. Both the
# shim's source (src-tauri/toolchain/linker_wrap.c) and this generator are
# tracked in git; only the compiled wrapper and this file are generated, so
# deleting them is always recoverable:
#
#     python scripts/build/ensure_gnu_linkchain.py
#
# The linker path MUST be absolute: cargo forwards it to rustc as `-C linker`,
# which resolves a relative path against an unpredictable working directory.
[target.{triple}]
linker = "{linker}"
# gcc derives its install tree from argv[0], and needs its bin dir on PATH to
# find collect2 / ld / as; a bare name only works when MSYS2 is already on the
# ambient PATH (it often is not, e.g. from a GUI-launched shell).
ar = "{ar}"
"""

# The archiver cargo must use for this target. It is a DIFFERENT binary from the
# compiler: the linker wrapper drives gcc, but `ar` archives rlibs and must be
# the binutils archiver, not gcc itself.
AR_NAME = "x86_64-w64-mingw32-gcc-ar.exe"

# Compiler output is echoed into the dev loop, so cap it: a noisy toolchain
# build must not bury the output the developer is actually reading.
MAX_COMPILER_OUTPUT_LINES = 10


def log(msg: str) -> None:
    print(f"[gnu-linkchain] {msg}", flush=True)


def find_gcc() -> Path | None:
    """Locate the mingw-w64 gcc, preferring an explicit MINGW_GCC override."""
    override = os.environ.get("MINGW_GCC")
    if override and Path(override).is_file():
        return Path(override)

    for root in GCC_SEARCH_ROOTS:
        candidate = Path(root) / GCC_EXE_NAME
        if candidate.is_file():
            return candidate

    found = shutil.which(GCC_EXE_NAME)
    return Path(found) if found else None


def needs_rebuild(force: bool) -> bool:
    if force:
        return True
    if not WRAPPER_EXE.is_file():
        return True
    # Rebuild when the tracked source is newer than the binary it produced.
    return WRAPPER_SRC.stat().st_mtime > WRAPPER_EXE.stat().st_mtime


def config_is_current(linker: Path, gcc: Path) -> bool:
    """True when config.toml already points at the artifacts we would write."""
    if not CARGO_CONFIG.is_file():
        return False
    text = CARGO_CONFIG.read_text(encoding="utf-8", errors="replace")
    return (
        f'linker = "{linker.as_posix()}"' in text
        and f'ar = "{AR_NAME}"' in text
        and f"[target.{TARGET_TRIPLE}]" in text
    )


def write_config(linker: Path, gcc: Path) -> None:
    CARGO_CONFIG.parent.mkdir(parents=True, exist_ok=True)
    CARGO_CONFIG.write_text(
        CONFIG_HEADER.format(
            triple=TARGET_TRIPLE,
            linker=linker.as_posix(),
            ar=AR_NAME,
        ),
        encoding="utf-8",
    )


def compile_wrapper(gcc: Path) -> None:
    """Compile the tracked source with the SAME gcc that will run it.

    Using the target's own compiler avoids depending on a separate host
    toolchain, and guarantees the wrapper matches the gcc it invokes.

    gcc locates its own subprograms (cc1, as, collect2, ld) relative to its
    install prefix, so it inherits the same environment the wrapper sets for
    itself: GCC_EXEC_PREFIX plus its bin dir on PATH. Without this, gcc exits
    non-zero with NO diagnostic when spawned from a shell (e.g. a GUI-launched
    cmd) that has never had MSYS2 on PATH.
    """
    TOOLCHAIN_DIR.mkdir(parents=True, exist_ok=True)
    staging = TOOLCHAIN_DIR / "linker-wrap.exe.new"
    # -Wno-format-truncation: the wrapper composes Windows paths into MAX_PATH
    # buffers, and gcc's analysis is pessimistic (it assumes every %s fills the
    # whole buffer, so every snprintf warns). These are false positives here: a
    # working Windows path is bounded by MAX_PATH by definition, which is
    # exactly the buffer size used. Left on, they buried the real dev-loop
    # output under ~80 lines of noise on every rebuild. -Wextra is kept so
    # genuine defects (unused vars, bad signatures) still surface.
    cmd = [
        str(gcc),
        "-O2",
        "-Wall",
        "-Wextra",
        "-Wno-format-truncation",
        "-o",
        str(staging),
        str(WRAPPER_SRC),
    ]

    env = dict(os.environ)
    prefix_root = gcc.parent.parent  # .../mingw64 from .../mingw64/bin
    env["GCC_EXEC_PREFIX"] = f"{prefix_root.as_posix()}/lib/gcc/"
    env["PATH"] = f"{gcc.parent.as_posix()};{env.get('PATH', '')}"

    proc = subprocess.run(cmd, capture_output=True, text=True, env=env)
    if proc.returncode != 0 or not staging.is_file():
        sys.stderr.write(proc.stdout + proc.stderr)
        raise SystemExit(f"[gnu-linkchain] failed to compile {WRAPPER_SRC}")

    # Replace only after a successful compile: a crash mid-write must not leave
    # a truncated wrapper that cargo would then invoke.
    staging.replace(WRAPPER_EXE)
    if proc.stderr.strip():
        # Never let compiler noise flood the dev loop; it buries the build
        # output and trains the reader to ignore the log. Show a bounded
        # sample plus the real count so nothing is silently hidden.
        lines = [ln for ln in proc.stderr.strip().splitlines() if ln.strip()]
        log(f"compiler warnings: {len(lines)} lines")
        for line in lines[:MAX_COMPILER_OUTPUT_LINES]:
            log(f"  {line}")
        if len(lines) > MAX_COMPILER_OUTPUT_LINES:
            log(
                f"  ... {len(lines) - MAX_COMPILER_OUTPUT_LINES} more lines "
                "suppressed; recompile manually for the full output"
            )


def purge_stale_scratch() -> None:
    """Remove leftovers from an older wrapper that leaked its obj-<pid> dirs.

    Only touches the generated dir, never the tracked source, and only removes
    the wrapper's own scratch patterns.
    """
    if not TOOLCHAIN_DIR.is_dir():
        return
    removed = 0
    for obj in TOOLCHAIN_DIR.glob("obj-*"):
        if obj.is_dir():
            shutil.rmtree(obj, ignore_errors=True)
            removed += 1
    for rsp in TOOLCHAIN_DIR.glob("link-*.rsp"):
        rsp.unlink(missing_ok=True)
    if removed:
        log(f"removed {removed} stale scratch dirs from an older wrapper")


def provision(force: bool) -> int:
    if sys.platform != "win32":
        # MSVC / non-Windows hosts do not need the shim at all. Never fail them.
        log("not Windows; GNU linker shim not required")
        return 0

    if not WRAPPER_SRC.is_file():
        sys.stderr.write(
            f"[gnu-linkchain] TRACKED SOURCE MISSING: {WRAPPER_SRC}\n"
            "The linker shim's source is missing from the checkout. Restore it\n"
            "with `git checkout -- src-tauri/toolchain/linker_wrap.c` (or clone\n"
            "the repo again). Do NOT hand-write a replacement.\n"
        )
        return 1

    gcc = find_gcc()
    if gcc is None:
        sys.stderr.write(
            "[gnu-linkchain] MSYS2/mingw-w64 GCC not found.\n"
            "Install MSYS2 (https://www.msys2.org/) and its mingw-w64 toolchain,\n"
            "or set MINGW_GCC to the full path of x86_64-w64-mingw32-gcc.exe.\n"
        )
        return 1

    rebuilt = False
    if needs_rebuild(force):
        log(f"compiling {WRAPPER_SRC.name} -> {WRAPPER_EXE.name}")
        compile_wrapper(gcc)
        rebuilt = True
    else:
        log("wrapper is up to date")

    purge_stale_scratch()

    if config_is_current(WRAPPER_EXE, gcc) and not rebuilt:
        log("cargo config already correct")
    else:
        write_config(WRAPPER_EXE, gcc)
        log(f"wrote {CARGO_CONFIG.relative_to(REPO_ROOT)}")

    log(f"ready: {WRAPPER_EXE}")
    return 0


def check() -> int:
    """Read-only verification, for the dev-loop preflight. Never writes."""
    if sys.platform != "win32":
        return 0

    if not WRAPPER_EXE.is_file():
        sys.stderr.write(
            f"[gnu-linkchain] MISSING: {WRAPPER_EXE}\n"
            "The MSYS2 linker shim is absent (deleted, or quarantined by AV).\n"
            "Repair it with:  python scripts/build/ensure_gnu_linkchain.py\n"
        )
        return 1

    if not CARGO_CONFIG.is_file():
        sys.stderr.write(
            f"[gnu-linkchain] MISSING: {CARGO_CONFIG}\nRepair it with:  python scripts/build/ensure_gnu_linkchain.py\n"
        )
        return 1

    # A config pointing at a path that no longer exists is the exact failure
    # this whole mechanism exists to prevent, so assert it explicitly.
    text = CARGO_CONFIG.read_text(encoding="utf-8", errors="replace")
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("linker = "):
            value = line.split("=", 1)[1].strip().strip('"')
            if value and not Path(value).is_file():
                sys.stderr.write(
                    f"[gnu-linkchain] config points at a missing file: {value}\n"
                    "Repair it with:  python scripts/build/ensure_gnu_linkchain.py\n"
                )
                return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Provision the GNU linker shim.")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="verify only, never write")
    group.add_argument("--force", action="store_true", help="recompile even if current")
    args = parser.parse_args()

    if args.check:
        return check()
    return provision(force=args.force)


if __name__ == "__main__":
    raise SystemExit(main())
