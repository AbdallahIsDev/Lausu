@pytest.mark.parametrize("name", sorted(FIXTURES))
def test_old_fixture_decrypts_exactly(name: str) -> None:
    """Every blob written by the old backend must decrypt to its exact plaintext."""
    plaintext, blob = FIXTURES[name]
    assert _text_crypto.decrypt_text(blob, KEY) == plaintext


@pytest.mark.parametrize("name", sorted(FIXTURES))
def test_new_encryption_matches_embedded_old_bytes(name: str) -> None:
    """Expected bytes were produced by cryptography AESGCM with AAD=None."""
    plaintext, blob = FIXTURES[name]
    assert _text_crypto._encrypt_with_nonce(plaintext, KEY, NONCE) == blob


@pytest.mark.parametrize("name", sorted(FIXTURES))
def test_new_random_blob_round_trips(name: str) -> None:
    plaintext, _ = FIXTURES[name]
    blob = _text_crypto.encrypt_text(plaintext, KEY)
    assert _text_crypto.decrypt_text(blob, KEY) == plaintext


@pytest.mark.parametrize("name", sorted(FIXTURES))
def test_wrong_key_returns_placeholder(name: str) -> None:
    _, blob = FIXTURES[name]
    assert _text_crypto.decrypt_text(blob, OTHER_KEY) == PLACEHOLDER


@pytest.mark.parametrize("region", ["ciphertext", "tag"])
def test_tampered_blob_fails_closed(region: str) -> None:
    _, blob = FIXTURES["ascii"]
    raw = bytearray(base64.b64decode(blob[len("enc:v1:") :]))
    raw[14 if region == "ciphertext" else -1] ^= 0x01
    tampered = "enc:v1:" + base64.b64encode(bytes(raw)).decode("ascii")
    assert _text_crypto.decrypt_text(tampered, KEY) == PLACEHOLDER


@pytest.mark.parametrize("length", [0, 12, 27])
def test_truncated_payload_returns_placeholder(length: int) -> None:
    _, blob = FIXTURES["ascii"]
    raw = base64.b64decode(blob[len("enc:v1:") :])[:length]
    truncated = "enc:v1:" + base64.b64encode(raw).decode("ascii")
    assert _text_crypto.decrypt_text(truncated, KEY) == PLACEHOLDER


def test_wrong_nonce_length_rejected() -> None:
    with pytest.raises(ValueError):
        _text_crypto._encrypt_with_nonce("x", KEY, b"short")


def test_auth_failure_never_leaks_plaintext() -> None:
    _, blob = FIXTURES["unicode"]
    raw = bytearray(base64.b64decode(blob[len("enc:v1:") :]))
    raw[-1] ^= 0x01
    tampered = "enc:v1:" + base64.b64encode(bytes(raw)).decode("ascii")
    result = _text_crypto.decrypt_text(tampered, KEY)
    assert result == PLACEHOLDER
    assert "مرحبا" not in result
